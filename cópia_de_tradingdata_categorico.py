# 2. Função para identificar o ponto de acurácia máxima e o ponto onde inicia o declínio
def get_max_and_decline_points(df_method):
    # Ordenar pelos números de features
    df_sorted = df_method.sort_values(by='Features')

    # Ponto com acurácia máxima
    max_idx = df_sorted['Accuracy'].idxmax()
    max_point = df_sorted.loc[max_idx]

    # Encontrar o ponto onde a acurácia começa a declinar:
    # Percorrer a lista ordenada e identificar o primeiro ponto em que a acurácia atual é menor que a anterior.
    df_list = df_sorted.to_dict('records')
    decline_point = None
    for i in range(1, len(df_list)):
        if df_list[i]['Accuracy'] < df_list[i-1]['Accuracy']:
            decline_point = df_list[i-1]
            break
    # Caso não haja declínio aparente, usamos o último ponto (ou poderíamos manter o mesmo do máximo)
    if decline_point is None:
        decline_point = df_sorted.iloc[-1]
    return max_point, decline_point

