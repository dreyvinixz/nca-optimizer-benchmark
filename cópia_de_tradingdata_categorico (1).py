# TRANSFORMERS CUSTOMIZADOS — feature selection dentro do CV
#
# Cada transformer faz fit apenas nos dados de treino do fold,
# sem vazar nenhuma informação do fold de validação.
# ═════════════════════════════════════════════════════════════

class InformationGainSelector(BaseEstimator, TransformerMixin):
    """Seleciona as top-k features por Information Gain (mutual_info_classif).
    fit() é chamado apenas com dados de treino do fold → sem leakage."""

    def __init__(self, k=1, feature_names=None, random_state=42):
        self.k = k
        self.feature_names = feature_names
        self.random_state = random_state

    def fit(self, X, y):
        scores = mutual_info_classif(X, y, random_state=self.random_state)
        self.selected_indices_ = np.argsort(scores)[::-1][:self.k]
        # ranking completo para uso externo
        self.ranked_indices_ = np.argsort(scores)[::-1]
        self.scores_ = scores
        return self

    def transform(self, X):
        return X[:, self.selected_indices_]


class ReliefFSelector(BaseEstimator, TransformerMixin):
    """Seleciona as top-k features por ReliefF.
    fit() é chamado apenas com dados de treino do fold → sem leakage."""

    def __init__(self, k=1, n_neighbors=10):
        self.k = k
        self.n_neighbors = n_neighbors

    def fit(self, X, y):
        relief = ReliefF(n_neighbors=self.n_neighbors,
                         n_features_to_select=X.shape[1])
        relief.fit(X, y)
        self.selected_indices_ = np.argsort(relief.feature_importances_)[::-1][:self.k]
        self.ranked_indices_   = np.argsort(relief.feature_importances_)[::-1]
        self.importances_      = relief.feature_importances_
        return self

    def transform(self, X):
        return X[:, self.selected_indices_]


class PCASelector(BaseEstimator, TransformerMixin):
    """Normaliza (StandardScaler) e aplica PCA dentro do fold.
    fit() é chamado apenas com dados de treino do fold → sem leakage."""

    def __init__(self, k=1):
        self.k = k

    def fit(self, X, y=None):
        self.scaler_ = StandardScaler()
        X_scaled = self.scaler_.fit_transform(X)

        self.pca_ = PCA(n_components=X.shape[1])
        self.pca_.fit(X_scaled)

        pca_importance = np.abs(self.pca_.components_).T @ self.pca_.explained_variance_ratio_
        self.selected_indices_ = np.argsort(pca_importance)[::-1][:self.k]
        self.ranked_indices_   = np.argsort(pca_importance)[::-1]
        self.pca_importance_   = pca_importance
        return self

    def transform(self, X):
        X_scaled = self.scaler_.transform(X)
        return X_scaled[:, self.selected_indices_]


class ClassifierAttributeSelector(BaseEstimator, TransformerMixin):
    """Seleciona as top-k features avaliando cada uma com uma Decision Tree (CV interno).
    fit() é chamado apenas com dados de treino do fold → sem leakage."""

    def __init__(self, k=1, max_depth=3, n_splits=5, random_state=42):
        self.k = k
        self.max_depth = max_depth
        self.n_splits = n_splits
        self.random_state = random_state

    def fit(self, X, y):
        skf = StratifiedKFold(n_splits=self.n_splits, shuffle=True,
                              random_state=self.random_state)
        scores = []
        for i in range(X.shape[1]):
            X_feat = X[:, i].reshape(-1, 1)
            dt = DecisionTreeClassifier(max_depth=self.max_depth,
                                        random_state=self.random_state)
            accs = cross_val_score(dt, X_feat, y, cv=skf, scoring='accuracy')
            scores.append(np.mean(accs))
        scores = np.array(scores)
        self.selected_indices_ = np.argsort(scores)[::-1][:self.k]
        self.ranked_indices_   = np.argsort(scores)[::-1]
        self.scores_           = scores
        return self

    def transform(self, X):
        return X[:, self.selected_indices_]


class CorrelationAttributeSelector(BaseEstimator, TransformerMixin):
    """Seleciona as top-k features por correlação ponto-bisserial.
    fit() é chamado apenas com dados de treino do fold → sem leakage."""

    def __init__(self, k=1):
        self.k = k

    def fit(self, X, y):
        scores = np.array([abs(pointbiserialr(y, X[:, i])[0])
                           for i in range(X.shape[1])])
        self.selected_indices_ = np.argsort(scores)[::-1][:self.k]
        self.ranked_indices_   = np.argsort(scores)[::-1]
        self.scores_           = scores
        return self

    def transform(self, X):
        return X[:, self.selected_indices_]


