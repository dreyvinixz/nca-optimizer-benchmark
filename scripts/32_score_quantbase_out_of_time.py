"""Score optimized models on a new Quantbase out-of-time dataset.

This script trains on the original 2024 train+validation block with the best
hyperparameters already found by the optimizer runs, then predicts a model-ready
Quantbase CSV generated by `31_import_quantbase_2026_intraday.py`.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    balanced_accuracy_score,
    f1_score,
    matthews_corrcoef,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.data_loader import load_legacy_dataset
from src.feature_selection import select_features
from src.models.cnn import fit_predict_cnn
from src.models.mlp import fit_predict_mlp
from src.models.rf_model import fit_predict_rf
from src.models.svm_model import fit_predict_svm
from src.objective import normalize_candidate
from src.preprocessing import drop_missing_rows, keep_numeric_features
from src.utils.io import load_project_configs


DEFAULT_NEW_DATASET = ROOT / "data" / "external" / "quantbase_win_2026_06_22_24_5m_model_ready.csv"
DEFAULT_OUTPUT_DIR = ROOT / "outputs" / "professor_presentation" / "live_simulation" / "quantbase_2026_out_of_time"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Train on legacy data and score Quantbase 2026 out-of-time data.")
    parser.add_argument("--new-dataset", type=Path, default=DEFAULT_NEW_DATASET)
    parser.add_argument("--experiment-root", type=Path, default=ROOT / "outputs" / "article_official")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--combos",
        nargs="+",
        default=["mlp:gwo", "rf:gwo", "cnn:de", "svm:gwo"],
        help="Model/optimizer pairs, e.g. mlp:gwo rf:gwo cnn:de.",
    )
    parser.add_argument("--cost-points", type=float, default=5.0)
    parser.add_argument("--min-confidence", type=float, default=0.55)
    parser.add_argument("--stop-points", type=float, default=None)
    parser.add_argument("--target-points", type=float, default=None)
    return parser.parse_args()


def load_train_and_new(new_dataset: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, pd.DataFrame, list[str]]:
    config = load_project_configs()
    exp = config["experiment"]
    legacy = load_legacy_dataset(
        config["paths"]["dataset"]["merged_output"],
        exp["data"]["datetime_column"],
        exp["data"]["target_column"],
        exp["data"]["label_mapping"],
    )
    legacy_numeric = keep_numeric_features(legacy.frame, legacy.feature_columns)
    selected = select_features(legacy_numeric, exp["data"]["selected_feature_indices"])

    legacy_modeling = selected + [legacy.target_column, legacy.datetime_column]
    legacy_frame = drop_missing_rows(legacy.frame, legacy_modeling).sort_values(legacy.datetime_column).reset_index(drop=True)
    train_end = int(len(legacy_frame) * float(exp["split"]["train_size"]))
    val_end = train_end + int(len(legacy_frame) * float(exp["split"]["validation_size"]))
    train_full = legacy_frame.iloc[:val_end].copy()

    new = load_legacy_dataset(
        new_dataset,
        exp["data"]["datetime_column"],
        exp["data"]["target_column"],
        exp["data"]["label_mapping"],
    )
    missing = sorted(set(selected) - set(new.frame.columns))
    if missing:
        raise ValueError(f"New dataset is missing selected training features: {missing}")
    new_required = selected + [new.target_column, new.datetime_column, "open", "high", "low", "close"]
    new_frame = drop_missing_rows(new.frame, new_required).sort_values(new.datetime_column).reset_index(drop=True)

    X_train = train_full[selected].to_numpy(dtype="float32")
    y_train = train_full[legacy.target_column].to_numpy(dtype=int)
    X_new = new_frame[selected].to_numpy(dtype="float32")
    y_new = new_frame[new.target_column].to_numpy(dtype=int)

    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train).astype("float32")
    X_new_scaled = scaler.transform(X_new).astype("float32")
    return X_train_scaled, y_train, X_new_scaled, y_new, new_frame, selected


def parse_combo(combo: str) -> tuple[str, str]:
    if ":" not in combo:
        raise ValueError(f"Invalid combo '{combo}'. Expected model:optimizer.")
    model, optimizer = combo.split(":", 1)
    return model.strip().lower(), optimizer.strip().lower()


def dispatch_model(
    model_type: str,
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_eval: np.ndarray,
    candidate: dict[str, Any],
    model_config: dict[str, Any],
    seed: int,
) -> tuple[np.ndarray, np.ndarray, str]:
    if model_type == "mlp":
        y_pred, y_proba, _, backend = fit_predict_mlp(X_train, y_train, X_eval, candidate, model_config, seed)
    elif model_type == "rf":
        y_pred, y_proba, _, backend = fit_predict_rf(X_train, y_train, X_eval, candidate, model_config, seed)
    elif model_type == "svm":
        y_pred, y_proba, _, backend = fit_predict_svm(X_train, y_train, X_eval, candidate, model_config, seed)
    elif model_type == "cnn":
        y_pred, y_proba, _, backend = fit_predict_cnn(X_train, y_train, X_eval, candidate, model_config, seed)
    else:
        raise ValueError(f"Unknown model type: {model_type}")
    return np.asarray(y_pred, dtype=int), np.asarray(y_proba, dtype=float), backend


def classification_metrics(y_true: np.ndarray, y_pred: np.ndarray, y_proba: np.ndarray) -> dict[str, float]:
    metrics = {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y_true, y_pred)),
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "mcc": float(matthews_corrcoef(y_true, y_pred)),
    }
    if len(np.unique(y_true)) > 1:
        metrics["auc_roc"] = float(roc_auc_score(y_true, y_proba))
        metrics["auc_pr"] = float(average_precision_score(y_true, y_proba))
    else:
        metrics["auc_roc"] = float("nan")
        metrics["auc_pr"] = float("nan")
    return metrics


def resolve_trade(
    direction: int,
    entry_price: float,
    high: float,
    low: float,
    close: float,
    stop_points: float | None,
    target_points: float | None,
) -> tuple[float, str, float]:
    if direction == 1:
        stop_hit = stop_points is not None and low <= entry_price - stop_points
        target_hit = target_points is not None and high >= entry_price + target_points
        if stop_hit:
            return -float(stop_points), "stop", entry_price - float(stop_points)
        if target_hit:
            return float(target_points), "target", entry_price + float(target_points)
        return close - entry_price, "close", close

    stop_hit = stop_points is not None and high >= entry_price + stop_points
    target_hit = target_points is not None and low <= entry_price - target_points
    if stop_hit:
        return -float(stop_points), "stop", entry_price + float(stop_points)
    if target_hit:
        return float(target_points), "target", entry_price - float(target_points)
    return entry_price - close, "close", close


def summarize_trades(trades: pd.DataFrame) -> dict[str, float | int]:
    if trades.empty:
        return {
            "total_trades": 0,
            "total_profit_points": 0.0,
            "mean_trade_points": 0.0,
            "win_rate": 0.0,
            "profit_factor": 0.0,
            "max_drawdown_points": 0.0,
            "sharpe_ratio_annualized": 0.0,
        }
    returns = trades["net_points"].astype(float)
    equity = returns.cumsum()
    gross_profit = float(returns[returns > 0].sum())
    gross_loss = float(abs(returns[returns < 0].sum()))
    drawdown = equity - equity.cummax()
    daily = trades.groupby(trades["entry_datetime"].dt.date)["net_points"].sum()
    sharpe = 0.0
    if len(daily) > 1 and daily.std(ddof=1) > 0:
        sharpe = float((daily.mean() / daily.std(ddof=1)) * math.sqrt(252))
    return {
        "total_trades": int(len(trades)),
        "total_profit_points": float(returns.sum()),
        "mean_trade_points": float(returns.mean()),
        "win_rate": float((returns > 0).mean()),
        "profit_factor": float(gross_profit / gross_loss) if gross_loss > 0 else float("inf"),
        "max_drawdown_points": float(drawdown.min()),
        "sharpe_ratio_annualized": sharpe,
    }


def replay_new_market(
    predictions: pd.DataFrame,
    market: pd.DataFrame,
    cost_points: float,
    min_confidence: float,
    stop_points: float | None,
    target_points: float | None,
) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    market = market.reset_index(drop=True).copy()
    for i in range(len(predictions) - 1):
        pred_row = predictions.iloc[i]
        entry = market.iloc[i + 1]
        confidence = max(float(pred_row["y_proba"]), 1.0 - float(pred_row["y_proba"]))
        if confidence < min_confidence:
            continue
        direction = 1 if int(pred_row["y_pred"]) == 1 else -1
        gross, exit_reason, exit_price = resolve_trade(
            direction,
            float(entry["open"]),
            float(entry["high"]),
            float(entry["low"]),
            float(entry["close"]),
            stop_points,
            target_points,
        )
        rows.append(
            {
                "row_id": int(i),
                "signal_datetime": pd.Timestamp(pred_row["datetime"]),
                "entry_datetime": pd.Timestamp(entry["datetime"]),
                "direction": "long" if direction == 1 else "short",
                "y_true": int(pred_row["y_true"]),
                "y_pred": int(pred_row["y_pred"]),
                "y_proba": float(pred_row["y_proba"]),
                "confidence": confidence,
                "entry_price": float(entry["open"]),
                "exit_price": float(exit_price),
                "gross_points": float(gross),
                "cost_points": float(cost_points),
                "net_points": float(gross - cost_points),
                "exit_reason": exit_reason,
            }
        )
    return pd.DataFrame(rows)


def main() -> None:
    args = parse_args()
    config = load_project_configs()
    X_train, y_train, X_new, y_new, new_market, selected_features = load_train_and_new(args.new_dataset)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    predictive_rows: list[dict[str, Any]] = []
    economic_rows: list[dict[str, Any]] = []
    all_trades: list[pd.DataFrame] = []

    for combo in args.combos:
        model_type, optimizer = parse_combo(combo)
        best_path = args.experiment_root / "metrics" / f"{model_type}_{optimizer}_best_by_seed.csv"
        if not best_path.exists():
            raise FileNotFoundError(f"Best-by-seed file not found: {best_path}")
        best = pd.read_csv(best_path)
        for row in best.itertuples(index=False):
            seed = int(row.seed)
            candidate = normalize_candidate(
                json.loads(row.decoded_hyperparameters),
                config["search_spaces"],
                model_type,
            )
            model_config = config["experiment"]["model"].copy()
            model_config["backend"] = "auto"
            model_config["probability"] = True
            y_pred, y_proba, backend = dispatch_model(
                model_type,
                X_train,
                y_train,
                X_new,
                candidate,
                model_config,
                seed + 200000,
            )

            pred = pd.DataFrame(
                {
                    "model_type": model_type,
                    "optimizer": optimizer,
                    "seed": seed,
                    "row_id": np.arange(len(y_pred)),
                    "datetime": new_market["datetime"].to_numpy(),
                    "y_true": y_new,
                    "y_pred": y_pred,
                    "y_proba": y_proba,
                }
            )
            pred.to_csv(args.output_dir / f"{model_type}_{optimizer}_seed{seed}_predictions.csv", index=False)

            metrics = classification_metrics(y_new, y_pred, y_proba)
            predictive_rows.append(
                {
                    "model_type": model_type,
                    "optimizer": optimizer,
                    "seed": seed,
                    "backend": backend,
                    **metrics,
                }
            )

            trades = replay_new_market(
                pred,
                new_market,
                cost_points=args.cost_points,
                min_confidence=args.min_confidence,
                stop_points=args.stop_points,
                target_points=args.target_points,
            )
            if not trades.empty:
                trades.insert(0, "seed", seed)
                trades.insert(0, "optimizer", optimizer)
                trades.insert(0, "model_type", model_type)
                all_trades.append(trades)
            economic_rows.append(
                {
                    "model_type": model_type,
                    "optimizer": optimizer,
                    "seed": seed,
                    **summarize_trades(trades),
                }
            )

    predictive = pd.DataFrame(predictive_rows)
    economic = pd.DataFrame(economic_rows)
    predictive.to_csv(args.output_dir / "predictive_by_seed.csv", index=False)
    economic.to_csv(args.output_dir / "economic_replay_by_seed.csv", index=False)

    predictive_combo = predictive.drop(columns=["seed"]).groupby(["model_type", "optimizer"], as_index=False).mean(numeric_only=True)
    economic_combo = economic.drop(columns=["seed"]).groupby(["model_type", "optimizer"], as_index=False).mean(numeric_only=True)
    seed_counts = predictive.groupby(["model_type", "optimizer"]).size().rename("n_seeds").reset_index()
    predictive_combo = predictive_combo.merge(seed_counts, on=["model_type", "optimizer"], how="left")
    economic_combo = economic_combo.merge(seed_counts, on=["model_type", "optimizer"], how="left")
    predictive_combo.to_csv(args.output_dir / "predictive_by_combo.csv", index=False)
    economic_combo.to_csv(args.output_dir / "economic_replay_by_combo.csv", index=False)

    if all_trades:
        pd.concat(all_trades, ignore_index=True).to_csv(args.output_dir / "economic_replay_trades.csv", index=False)

    metadata = {
        "new_dataset": str(args.new_dataset),
        "experiment_root": str(args.experiment_root),
        "selected_features": selected_features,
        "train_rows": int(len(y_train)),
        "new_rows": int(len(y_new)),
        "cost_points": args.cost_points,
        "min_confidence": args.min_confidence,
        "stop_points": args.stop_points,
        "target_points": args.target_points,
        "combos": args.combos,
    }
    (args.output_dir / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"Saved predictive/economic out-of-time results to {args.output_dir}")
    print(predictive_combo.to_string(index=False))
    print(economic_combo.to_string(index=False))


if __name__ == "__main__":
    main()
